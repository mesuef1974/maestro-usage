METRICS = [dict(key=k, name=n, unit=u, source=s, window=w, pages=p, definition=d) for k, n, u, s, w, p, d in _ROWS]
BY_KEY = {m["key"]: m for m in METRICS}


def for_page(page_file):
    return [m for m in METRICS if page_file in m["pages"]]


def defs_html(page_file):
    """قائمة التعريفات لصفحة: الاسم ثم (الوحدة · المصدر · النافذة) ثم التعريف."""
    out = []
    for m in for_page(page_file):
        meta = " · ".join(html.escape(x) for x in (m["unit"], m["source"], m["window"]) if x and x != "—")
        out.append('<dt>%s<span class="mu">%s</span></dt><dd>%s</dd>' % (html.escape(m["name"]), meta, m["definition"]))
    return "<dl>%s</dl>" % "".join(out)
